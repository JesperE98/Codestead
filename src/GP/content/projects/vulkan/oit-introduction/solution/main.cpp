    VkDescriptorSetLayout descriptorSetLayout;
    VkPipelineLayout pipelineLayout;
    VkPipeline solidPipeline; // learnopengl's solidShader
    VkPipeline transparentPipeline; // learnopengl's transparentShader
    // TODO: the pipelines of the composite pass and the final pass

    VkCommandPool commandPool;

    VkImage depthImage;
    VkDeviceMemory depthImageMemory;
    VkImageView depthImageView;

    // TODO: the off-screen framebuffers and their images

    VkSampler colorBufferSampler; // for the render targets: clamp to the edge

    VkBuffer vertexBuffer;

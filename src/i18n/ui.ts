export const UI: Record<Lang, Dict> = { sv, en, es, zh, hi, ar, pt, fr, de, ru, ja };

/** Översätter en nyckel och fyller i {platshållare}. */
export function translate(lang: Lang, key: UiKey, params: Record<string, string | number> = {}): string {
  let text: string = key;
  for (const l of fallbackChain(lang)) {
    const v = UI[l][key];
    if (v !== undefined) {
      text = v;
      break;
    }
  }
  return text.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m));
}

export type Translate = (key: UiKey, params?: Record<string, string | number>) => string;

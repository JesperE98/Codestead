export interface Iface {
  index: number;
  name: string;
  flags: string;
  mtu: number;
  qdisc: string;
  state: 'UP' | 'DOWN' | 'UNKNOWN';
  linkType: string;
  mac: string;
  brd: string;
  inet: { addr: string; prefix: number; brd?: string; scope: string; extra: string; lft: string }[];
  inet6: { addr: string; prefix: number; scope: string; extra: string }[];
}

/** Länklokal IPv6-adress gjord av MAC-adressen (EUI-64). */
function linkLocal(mac: string): string {
  const b = mac.split(':').map((x) => parseInt(x, 16));
  b[0] ^= 2;
  const hex = (x: number, y: number) => ((x << 8) | y).toString(16);
  return `fe80::${hex(b[0], b[1])}:${hex(b[2], 0xff)}:${hex(0xfe, b[3])}:${hex(b[4], b[5])}`;
}


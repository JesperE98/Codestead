/** Skal som låtsas vara servern (192.168.1.10) och inte elevens dator. */
const REMOTE = new WeakSet<Shell>();

export function markAsServer(sh: Shell): void {
  REMOTE.add(sh);
}

export function isServer(sh: Shell): boolean {
  return REMOTE.has(sh);
}

/** Datorns egen adress i det lokala nätet. */
export function myIp(sh: Shell): string {
  return isServer(sh) ? SERVER_IP : MY_IP;
}

function myMac(sh: Shell): string {
  return isServer(sh) ? SERVER_MAC : MY_MAC;
}

const LINK_DOWN_FLAG = `net:${IFACE}:down`;

export function linkUp(sh: Shell): boolean {
  return !sh.flags[LINK_DOWN_FLAG];
}

export function setLinkUp(sh: Shell, up: boolean): void {
  if (up) delete sh.flags[LINK_DOWN_FLAG];
  else sh.flags[LINK_DOWN_FLAG] = true;
}

/** Ubuntu och Fedora använder systemd-resolved med en lokal DNS-stub på 127.0.0.53. */
export function usesResolved(distro: Distro): boolean {
  return distro.id === 'ubuntu' || distro.family === 'redhat';
}

export function resolvConf(distro: Distro): string {
  if (usesResolved(distro)) {
    return (
      '# This is /run/systemd/resolve/stub-resolv.conf managed by man:systemd-resolved(8).\n' +
      '# Do not edit.\n#\n' +
      '# This file might be symlinked as /etc/resolv.conf. If you\'re looking at\n' +
      '# /etc/resolv.conf and seeing this text, you have followed the symlink.\n#\n' +
      '# Run "resolvectl status" to see details about the uplink DNS servers\n' +
      '# currently in use.\n\n' +
      'nameserver 127.0.0.53\noptions edns0 trust-ad\nsearch lan\n'
    );
  }
  return `# Generated by NetworkManager\nsearch lan\nnameserver ${GATEWAY}\n`;
}

/** Programfilen /usr/local/bin/minserver. */
export function minserverBinary(): FsNode {
  const node = makeFile(`${ELF}\u0002\u0001\u0001 (simulerad binärfil: minserver)`, 'root', 0o755);
  node.size = 48_312;
  return node;
}

// ---------- Adresser ----------

export function isIPv4(s: string): boolean {
  const parts = s.split('.');
  return parts.length === 4 && parts.every((p) => /^\d{1,3}$/.test(p) && Number(p) <= 255);
}

export function isLoopback(ip: string): boolean {
  return ip.startsWith('127.') || ip === '0.0.0.0' || ip === '::1';
}

/** Är adressen datorn själv (loopback eller den egna adressen)? */
export function isLocal(sh: Shell, ip: string): boolean {
  return isLoopback(ip) || ip === myIp(sh);
}


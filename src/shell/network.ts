// ---------- DNS ----------

export type DnsStatus = 'NOERROR' | 'NXDOMAIN' | 'SERVFAIL';

export interface DnsAnswer {
  status: DnsStatus;
  a: string[];
  aaaa: string[];
}

/** Namnservern i /etc/resolv.conf (första raden "nameserver ..."), eller null. */
export function nameserver(sh: Shell): string | null {
  const conf = readSystemFile(sh, '/etc/resolv.conf');
  if (conf === null) return null;
  for (const line of conf.split('\n')) {
    const m = /^\s*nameserver\s+(\S+)/.exec(line);
    if (m) return m[1];
  }
  return null;
}

/** Svarar adressen på DNS-frågor (och går den att nå)? */
export function isDnsServer(sh: Shell, ip: string): boolean {
  if (ip === '127.0.0.53') return usesResolved(sh.distro);
  if (reach(sh, ip) !== 'ok') return false;
  if (ip === GATEWAY) return true;
  return !!internetHostByIp(ip)?.dns;
}

/**
 * Frågar en DNS-server. null betyder att servern inte gick att nå.
 * DNS känner bara till internet – inte /etc/hosts och inte namn i det lokala nätet.
 */
export function dnsQuery(sh: Shell, name: string, server: string | null = nameserver(sh)): DnsAnswer | null {
  if (!server || !isDnsServer(sh, server)) return null;
  // Stubben på 127.0.0.53 svarar alltid, men behöver nätet för att fråga vidare.
  if (!linkUp(sh)) return { status: 'SERVFAIL', a: [], aaaa: [] };
  const n = normName(name);
  if (n === 'localhost') return { status: 'NOERROR', a: ['127.0.0.1'], aaaa: ['::1'] };
  const host = internetHostByName(n);
  if (!host) return { status: 'NXDOMAIN', a: [], aaaa: [] };
  return { status: 'NOERROR', a: host.a, aaaa: host.aaaa ?? [] };
}

/** Omvänt uppslag (PTR) i DNS: IP-adress → namn. */
export function dnsReverse(ip: string): string | null {
  if (ip === '127.0.0.1') return 'localhost';
  return internetHostByIp(ip)?.names[0] ?? null;
}

export function readSystemFile(sh: Shell, path: string): string | null {
  const node = sh.vfs.tryLookup(path, sh.rootUser());
  return node?.type === 'file' ? (node.content ?? '') : null;
}

/** Raderna i /etc/hosts som [ip, namn...]. */
export function hostsEntries(sh: Shell): { ip: string; names: string[] }[] {
  const content = readSystemFile(sh, '/etc/hosts') ?? '';
  const entries: { ip: string; names: string[] }[] = [];
  for (const raw of content.split('\n')) {
    const fields = raw.replace(/#.*/, '').trim().split(/\s+/).filter(Boolean);
    if (fields.length >= 2) entries.push({ ip: fields[0], names: fields.slice(1) });
  }
  return entries;
}

export type Resolved =
  | { ok: true; ip: string; /** Namnet som skrevs (eller IP-adressen). */ name: string; source: 'literal' | 'hosts' | 'dns' }
  | { ok: false; error: 'notfound' | 'tempfail' };

/** Slår upp ett namn som systemet gör: först /etc/hosts, sedan DNS. Bara IPv4. */
export function resolveHost(sh: Shell, name: string): Resolved {
  if (isIPv4(name)) return { ok: true, ip: name, name, source: 'literal' };
  const n = normName(name);
  for (const e of hostsEntries(sh)) {
    if (isIPv4(e.ip) && e.names.some((x) => x.toLowerCase() === n)) return { ok: true, ip: e.ip, name, source: 'hosts' };
  }
  const answer = dnsQuery(sh, n);
  if (!answer || answer.status === 'SERVFAIL') return { ok: false, error: 'tempfail' };
  if (!answer.a.length) return { ok: false, error: 'notfound' };
  return { ok: true, ip: answer.a[0], name, source: 'dns' };
}

/** Text för ett misslyckat uppslag, som glibc skriver den. */
export function resolveErrorText(error: 'notfound' | 'tempfail'): string {
  return error === 'notfound' ? 'Name or service not known' : 'Temporary failure in name resolution';
}

/** Namnet som svaren från en adress visas med (som ping gör): /etc/hosts först, sedan DNS. */
export function reverseName(sh: Shell, ip: string): string | null {
  for (const e of hostsEntries(sh)) if (e.ip === ip) return e.names[0];
  if (ip === GATEWAY && usesResolved(sh.distro)) return '_gateway';
  return dnsReverse(ip);
}

// ---------- Nåbarhet ----------

export type Reach = 'ok' | 'netunreach' | 'hostunreach' | 'timeout';

/** Kan datorn nå adressen? */
export function reach(sh: Shell, ip: string): Reach {
  if (isLocal(sh, ip)) return 'ok';
  if (!linkUp(sh)) return 'netunreach';
  if (ip.startsWith(LAN_PREFIX)) return [GATEWAY, SERVER_IP, MY_IP].includes(ip) ? 'ok' : 'hostunreach';
  return internetHostByIp(ip) ? 'ok' : 'timeout';
}

/** Ett tal mellan 0 och 1 som alltid blir samma för samma indata. */
function noise(seed: string): number {
  let h = 2166136261;
  for (let i = 0; i < seed.length; i++) h = Math.imul(h ^ seed.charCodeAt(i), 16777619);
  return ((h >>> 0) % 10_000) / 10_000;
}

/** Svarstid i millisekunder för ett paket till adressen. */
export function rtt(sh: Shell, ip: string, seq: number): number {
  const n = noise(`${ip}#${seq}`);
  if (isLocal(sh, ip)) return 0.025 + n * 0.03;
  if (ip === GATEWAY) return 0.45 + n * 0.5;
  if (ip.startsWith(LAN_PREFIX)) return 0.3 + n * 0.4;
  const base = 6 + noise(ip) * 25;
  return base + n * 2.5;
}

export function ttl(sh: Shell, ip: string): number {
  if (isLocal(sh, ip) || ip.startsWith(LAN_PREFIX)) return 64;
  return 50 + Math.floor(noise(`ttl${ip}`) * 9);
}

/** Vägen dit (för traceroute): routrarna paketet passerar, sist målet. */
export function hops(sh: Shell, ip: string): (string | null)[] {
  if (isLocal(sh, ip) || ip.startsWith(LAN_PREFIX)) return [ip];
  const path: (string | null)[] = [GATEWAY, '100.64.0.1', '198.51.100.1', null, '203.0.113.1'];
  return reach(sh, ip) === 'ok' ? [...path, ip] : path;
}


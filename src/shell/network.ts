export interface HttpResponse {
  status: number;
  reason: string;
  /** "HTTP/1.1", "HTTP/1.0" eller "HTTP/2". */
  version: string;
  headers: [string, string][];
  body: string;
}

const REASONS: Record<number, string> = { 200: 'OK', 301: 'Moved Permanently', 400: 'Bad Request', 404: 'Not Found' };

export function byteLength(s: string): number {
  return new TextEncoder().encode(s).length;
}

function httpDate(): string {
  return new Date().toUTCString();
}

const MINSERVER_PAGES: Record<string, Page> = {
  '/': html('Hello from minserver!', 'This page is served by the process <b>minserver</b> on port 8080 of your own computer.'),
  '/om.html': html('About minserver', 'minserver 1.0 is a tiny practice web server. Its log is in ~/dokument/server.log.'),
  '/rapport': text('Report: 12 requests today, 3 errors, 1 slow request.\n'),
};
MINSERVER_PAGES['/index.html'] = MINSERVER_PAGES['/'];

const SERVER_PAGES: Record<string, Page> = {
  '/': html('server.lan', 'The school server. Log in with: ssh elev@server.lan'),
  '/hej.txt': text('Hej från servern!\n'),
};

const ROUTER_PAGES: Record<string, Page> = {
  '/': html('Router login', 'Log in to configure your home router (192.168.1.1).'),
};

/**
 * Svaret på en HTTP-förfrågan. Förutsätter att connect() gav 'ok'.
 * Returnerar en sträng med ett fel om tjänsten inte talar HTTP.
 */
export function httpRequest(
  sh: Shell,
  ip: string,
  port: number,
  https: boolean,
  hostHeader: string,
  path: string,
): HttpResponse | 'not-http' | 'tls-error' | 'empty' {
  const svc = service(sh, ip, port);
  if (svc === 'ssh') return 'not-http';
  if (svc === 'dns') return 'empty';
  if (https && svc !== 'https') return 'tls-error';
  const p = path.split('?')[0] || '/';

  if (svc === 'minserver') {
    return respond('HTTP/1.0', MINSERVER_PAGES[p], [['Server', 'minserver/1.0']]);
  }
  if (ip === SERVER_IP) return respond('HTTP/1.1', SERVER_PAGES[p], [['Server', 'nginx/1.26.3']]);
  if (ip === GATEWAY) return respond('HTTP/1.1', ROUTER_PAGES[p], [['Server', 'lighttpd/1.4.76']]);

  const host = internetHostByIp(ip)!;
  if (!https && svc === 'https') {
    return respond('HTTP/1.1', html('400 The plain HTTP request was sent to HTTPS port', 'Use https:// instead.'), [], 400);
  }
  if (!https && host.redirectHttp) {
    const location = `https://${hostHeader}${p}`;
    const body = `<html>\r\n<head><title>301 Moved Permanently</title></head>\r\n<body>\r\n<center><h1>301 Moved Permanently</h1></center>\r\n<hr><center>nginx</center>\r\n</body>\r\n</html>\r\n`;
    return {
      status: 301,
      reason: REASONS[301],
      version: 'HTTP/1.1',
      headers: [
        ['Server', 'nginx'],
        ['Date', httpDate()],
        ['Content-Type', 'text/html'],
        ['Content-Length', String(byteLength(body))],
        ['Connection', 'keep-alive'],
        ['Location', location],
      ],
      body,
    };
  }
  return respond(https ? 'HTTP/2' : 'HTTP/1.1', host.pages[p], []);
}

function respond(version: string, page: Page | undefined, extra: [string, string][], status = page ? 200 : 404): HttpResponse {
  const p = page ?? html('404 Not Found', 'The requested URL was not found on this server.');
  const headers: [string, string][] = [
    ['Content-Type', p.type],
    ['Content-Length', String(byteLength(p.body))],
    ['Date', httpDate()],
    ...extra,
  ];
  const h2 = version === 'HTTP/2';
  return {
    status,
    reason: REASONS[status] ?? '',
    version,
    headers: h2 ? headers.map(([k, v]) => [k.toLowerCase(), v]) : headers,
    body: p.body,
  };
}

const allFamilies: Family[] = ["debian", "arch", "redhat"];

function same(name: string): Obj<string> {
  return rec({ debian: name, arch: name, redhat: name });
}

/** A Partial<Record<Family, string>> literal: only the families given (in the order debian, arch, redhat). */
function rec(r: { debian?: string; arch?: string; redhat?: string }): Obj<string> {
  const o = new Map<Family, string>();
  if (r.debian !== undefined) o.set("debian", r.debian);
  if (r.arch !== undefined) o.set("arch", r.arch);
  if (r.redhat !== undefined) o.set("redhat", r.redhat);
  return o;
}


// ---------- The local network ----------

export const Iface = "enp0s3";
export const LanPrefix = "192.168.1.";
/** MY_IP in the TypeScript original (renamed in C#: a constant and the method myIp() cannot share a name). */
export const MyIpAddress = "192.168.1.42";
export const Gateway = "192.168.1.1";
export const ServerIp = "192.168.1.10";
export const ServerName = "server";
export const MyMacAddr = "08:00:27:3a:5c:e1";
export const ServerMac = "08:00:27:7b:10:0a";
export const GatewayMac = "3c:84:6a:12:34:56";

/** Shells that pretend to be the server (192.168.1.10) and not the student's computer. */
const remote = new WeakSet<Shell>();

export function markAsServer(sh: Shell): void {
  remote.add(sh);
}

export function isServer(sh: Shell): boolean {
  return remote.has(sh);
}

/** The computer's own address on the local network. */
export function myIp(sh: Shell): string {
  return isServer(sh) ? ServerIp : MyIpAddress;
}

export function myMac(sh: Shell): string {
  return isServer(sh) ? ServerMac : MyMacAddr;
}

const linkDownFlag = `net:${Iface}:down`;

export function linkUp(sh: Shell): boolean {
  return sh.flags.get(linkDownFlag) !== true;
}

export function setLinkUp(sh: Shell, up: boolean): void {
  if (up) sh.flags.delete(linkDownFlag);
  else sh.flags.set(linkDownFlag, true);
}

/** Ubuntu and Fedora use systemd-resolved with a local DNS stub on 127.0.0.53. */
export function usesResolved(distro: Distro): boolean {
  return distro.id === "ubuntu" || distro.family === "redhat";
}

export function resolvConf(distro: Distro): string {
  if (usesResolved(distro)) {
    return (
      "# This is /run/systemd/resolve/stub-resolv.conf managed by man:systemd-resolved(8).\n" +
      "# Do not edit.\n#\n" +
      "# This file might be symlinked as /etc/resolv.conf. If you're looking at\n" +
      "# /etc/resolv.conf and seeing this text, you have followed the symlink.\n#\n" +
      '# Run "resolvectl status" to see details about the uplink DNS servers\n' +
      "# currently in use.\n\n" +
      "nameserver 127.0.0.53\noptions edns0 trust-ad\nsearch lan\n"
    );
  }
  return `# Generated by NetworkManager\nsearch lan\nnameserver ${Gateway}\n`;
}

/** The program file /usr/local/bin/myserver. */
export function myserverBinary(): FsNode {
  const node = VfsLib.makeFile(`${VfsLib.Elf}\u0002\u0001\u0001 (simulated binary: myserver)`, "root", Js.oct(755));
  node.size = 48_312;
  return node;
}

// ---------- Addresses ----------

const octetRe = /^[0-9]{1,3}$/;

export function isIPv4(s: string): boolean {
  const parts = s.split(".");
  return parts.length === 4 && parts.every((p) => octetRe.test(p) && Js.number(p) <= 255);
}

export function isLoopback(ip: string): boolean {
  return ip.startsWith("127.") || ip === "0.0.0.0" || ip === "::1";
}

/** Is the address the computer itself (loopback or its own address)? */
export function isLocal(sh: Shell, ip: string): boolean {
  return isLoopback(ip) || ip === myIp(sh);
}

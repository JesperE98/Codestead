const view = new DataView(new ArrayBuffer(8));
function f64(hex: string): number {
  view.setBigUint64(0, BigInt("0x" + hex));
  return view.getFloat64(0);
}
function hex(x: number): string {
  view.setFloat64(0, x);
  return view.getBigUint64(0).toString(16).padStart(16, "0");
}
/** The bits of x, or "nan" for every NaN (the C code's NaN results are any NaN). */
const bitsOf = (x: number): string => (Number.isNaN(x) ? "nan" : hex(x));

type Unary = "sin" | "cos" | "tan" | "asin" | "acos" | "atan" | "exp" | "log" | "log2";
const UNARY: Record<Unary, (x: number) => number> = {
  sin: libm.sin, cos: libm.cos, tan: libm.tan, asin: libm.asin, acos: libm.acos, atan: libm.atan, exp: libm.exp, log: libm.log, log2: libm.log2,
};
const BINARY: Record<"pow" | "atan2", (y: number, x: number) => number> = { pow: libm.pow, atan2: libm.atan2 };

function run(name: string, args: string): number {
  if (name in BINARY) {
    const [a, b] = args.split(":") as [string, string];
    return BINARY[name as "pow" | "atan2"](f64(a), f64(b));
  }
  return UNARY[name as Unary](f64(args));
}


describe("libm", () => {
  it("gives glibc's exp, log, log2 and pow bit for bit", () => {
    const cases = VECTORS.filter(([name]) => ["exp", "log", "log2", "pow"].includes(name));
    expect(cases.length).toBeGreaterThan(500);
    for (const [name, args, expected] of cases) expect(`${name}(${args}) = ${bitsOf(run(name, args))}`).toBe(`${name}(${args}) = ${bitsOf(f64(expected))}`);
  });

  it("gives the correctly rounded sin, cos, tan, asin, acos, atan and atan2 – glibc's result but where glibc is off in the last bit", () => {
    const cases = VECTORS.filter(([name]) => !["exp", "log", "log2", "pow"].includes(name));
    expect(cases.length).toBeGreaterThan(800);
    let differ = 0;
    for (const [name, args, expected, glibc] of cases) {
      const r = run(name, args);
      expect(`${name}(${args}) = ${bitsOf(r)}`).toBe(`${name}(${args}) = ${bitsOf(f64(expected))}`);
      if (glibc !== undefined) {
        differ++;
        // glibc's result is the neighbour: one unit in the last place away
        expect(Math.abs(Number(BigInt("0x" + glibc) - BigInt("0x" + expected)))).toBe(1);
      }
    }
    expect(differ).toBeGreaterThan(40); // the cases where glibc is not correctly rounded
  });

  it("handles the special values as C does", () => {
    const pi = 3.141592653589793, half = 1.5707963267948966;
    const same = (a: number, b: number): void => expect(Object.is(a, b) || (Number.isNaN(a) && Number.isNaN(b)), `${a} vs ${b}`).toBe(true);
    for (const f of [libm.sin, libm.tan, libm.asin, libm.atan]) {
      same(f(0), 0);
      same(f(-0), -0);
      same(f(NaN), NaN);
    }
    for (const f of [libm.sin, libm.cos, libm.tan]) {
      same(f(Infinity), NaN);
      same(f(-Infinity), NaN);
    }
    same(libm.cos(0), 1);
    same(libm.cos(-0), 1);
    same(libm.asin(1), half);
    same(libm.asin(-1), -half);
    same(libm.asin(1.0000000000000002), NaN);
    same(libm.acos(1), 0);
    same(libm.acos(-1), pi);
    same(libm.acos(0), half);
    same(libm.acos(-2), NaN);
    same(libm.atan(Infinity), half);
    same(libm.atan(-Infinity), -half);
    same(libm.atan2(0, 0), 0);
    same(libm.atan2(-0, 0), -0);
    same(libm.atan2(0, -0), pi);
    same(libm.atan2(-0, -0), -pi);
    same(libm.atan2(1, 0), half);
    same(libm.atan2(-1, -0), -half);
    same(libm.atan2(Infinity, Infinity), pi / 4);
    same(libm.atan2(-Infinity, -Infinity), (-3 * pi) / 4);
    same(libm.atan2(3, -Infinity), pi);
    same(libm.atan2(-3, Infinity), -0);
    same(libm.atan2(NaN, 1), NaN);
    same(libm.exp(0), 1);
    same(libm.exp(-Infinity), 0);
    same(libm.exp(Infinity), Infinity);
    same(libm.exp(710), Infinity);
    same(libm.exp(-746), 0);
    same(libm.exp(NaN), NaN);
    for (const f of [libm.log, libm.log2]) {
      same(f(1), 0);
      same(f(0), -Infinity);
      same(f(-0), -Infinity);
      same(f(-1), NaN);
      same(f(Infinity), Infinity);
      same(f(NaN), NaN);
    }
    same(libm.log2(8), 3);
    same(libm.log2(2 ** -1074), -1074);
    same(libm.pow(2, 10), 1024);
    same(libm.pow(2, -1074), 2 ** -1074);
    same(libm.pow(2, 1024), Infinity);
    same(libm.pow(NaN, 0), 1);
    same(libm.pow(1, NaN), 1);
    same(libm.pow(-1, Infinity), 1);
    same(libm.pow(0, -1), Infinity);
    same(libm.pow(-0, -1), -Infinity);
    same(libm.pow(-0, -2), Infinity);
    same(libm.pow(-0, 3), -0);
    same(libm.pow(-8, 1 / 3), NaN);
    same(libm.pow(-2, 3), -8);
    same(libm.pow(-2, -1075), -0);
    same(libm.pow(0.5, Infinity), 0);
    same(libm.pow(2, -Infinity), 0);
    same(libm.pow(Infinity, -1), 0);
    same(libm.pow(-Infinity, 3), -Infinity);
  });

  it("fma rounds a*b + c once (hard cases: ties, cancellation, subnormal and overflowing results, special values)", () => {
    expect(FMA.length).toBeGreaterThan(500);
    for (const c of FMA) {
      const [a, b, d, r] = c.split(":").map(f64) as [number, number, number, number];
      expect(`fma(${c.slice(0, 50)}) = ${bitsOf(libm.fma(a, b, d))}`).toBe(`fma(${c.slice(0, 50)}) = ${bitsOf(r)}`);
    }
    // (1+2^-52)^2 - 2^-52 = 1 + 2^-52 + 2^-104 (one rounding, not two); 1 + 2^-53 is a tie (to even), just above it not
    expect(libm.fma(1 + 2 ** -52, 1 + 2 ** -52, -(2 ** -52))).toBe(1 + 2 ** -52);
    expect(libm.fma(2 ** -53, 1, 1)).toBe(1);
    expect(libm.fma(2 ** -53 + 2 ** -105, 1, 1)).toBe(1 + 2 ** -52);
    expect(libm.fma(0.1, 10, -1)).toBe(5.551115123125783e-17); // 0.1*10 is not 1 exactly
  });

  it("stands in for every transcendental Math function in the simulator's sources", () => {
    const src = join(Repo.root, "ts", "packages", "gp-gpu", "src");
    const files: string[] = [];
    const walk = (dir: string): void => {
      for (const f of readdirSync(dir)) {
        const p = join(dir, f);
        if (statSync(p).isDirectory()) walk(p);
        else if (p.endsWith(".ts") && !/[/\\]internal[/\\]libm[^/\\]*\.ts$/.test(p)) files.push(p);
      }
    };
    walk(src);
    const offenders = files.filter((f) => /\bMath\.(sin|cos|tan|asin|acos|atan|atan2|exp|expm1|log|log2|log10|log1p|pow|sinh|cosh|tanh|asinh|acosh|atanh|cbrt|hypot)\b/.test(readFileSync(f, "utf8")));
    expect(offenders).toEqual([]);
  });
});
